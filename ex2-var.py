# 변수의 작명 규칙
# 1. 변수 이름은 문자, 숫자, 밑줄(_)로 구성될 수 있습니다.
# 2. 변수 이름은 숫자로 시작할 수 없습니다.
# 3. 변수 이름은 대소문자를 구분합니다.
# 4. 예약어(키워드)는 변수 이름으로 사용할 수 없습니다.
# 5. 권장 : 두 단어 이상을 사용하되, 밑줄(_)로 연결하거나 두번째 단어부터 대문자로 시작하는 카멜표기법을 사용합니다.
